let uid = 0
function nextId(prefix: string) {
  uid += 1
  return `${prefix}-${uid}`
}

function slugify(name: string) {
  return name
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

interface FoodInput {
  name: string
  tagline: string
  description: string
  categorySlug: Food['categorySlug']
  price: number
  spiceLevel: Food['spiceLevel']
  isVeg?: boolean
  rating?: number
  reviewCount?: number
  bestseller?: boolean
  image: string
  sizes?: SizeOption[]
  addOns?: AddOn[]
}

function food(input: FoodInput): Food {
  const slug = slugify(input.name)
  return {
    id: nextId('food'),
    slug,
    name: input.name,
    tagline: input.tagline,
    description: input.description,
    categorySlug: input.categorySlug,
    price: input.price,
    spiceLevel: input.spiceLevel,
    isVeg: input.isVeg ?? false,
    rating: input.rating ?? 4.5,
    reviewCount: input.reviewCount ?? 128,
    bestseller: input.bestseller ?? false,
    images: [input.image],
    sizes: input.sizes,
    addOns: input.addOns,
  }
}

